import type { compareQuality, qualityGate } from '#@/bench/quality.ts';
import type { runBenchmark } from '#@/bench/run.ts';

type Report = Awaited<ReturnType<typeof runBenchmark>>;
export interface MarkdownReport extends Report {
  scene: string;
  revision: string;
  sourceSha256: string;
  node: string;
  concurrency: number;
  execution: { mode: string; workers: number; lanes: number };
  comparison?: ReturnType<typeof compareQuality> & { speedup?: number };
  prototype?: {
    implementation: string;
    sourceSha256: string;
    binarySha256?: string;
    locomotionLabelLimit?: number;
    nativeLocomotion?: boolean;
    nativeCollision?: boolean;
    nativeGroundTrace?: boolean;
    nativeGoals?: boolean;
    nativeCandidate?: boolean;
  };
  catalogTraining?: {
    algorithm: 'approximate-static-actions';
    ids: string[];
    wallMs: number;
    completed: number;
    stats: { added: number; scopes: number };
  };
  workingTreeDirty?: boolean;
  qualityGate?: ReturnType<typeof qualityGate>;
}
const number = (value: number | null, digits = 3) =>
  value === null ? 'n/a' : value.toFixed(digits);
const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function benchmarkMarkdown(report: MarkdownReport): string {
  const { batch, comparison } = report;
  const rows = [
    '> This message is generated by AI.',
    '',
    '<!-- ganglia-benchmark-results -->',
    '',
    `Ganglia benchmark: **${cell(report.scene)}**, ${batch.results.length} queries, ${report.execution.workers || 1} worker(s), ${report.concurrency} lane(s).`,
    '',
    '| Metric | Result |',
    '| --- | ---: |',
    `| Batch throughput | ${number(batch.queriesPerSecond, 5)} queries/s |`,
    `| Batch wall time | ${number(batch.wallMs / 1000)} s |`,
    ...(batch.meanSerialQueryMs === undefined
      ? []
      : [
          `| Mean serial query wall time (batch / queries) | ${number(batch.meanSerialQueryMs)} ms |`,
        ]),
    `| Excluded full-batch prewarm | ${number(report.prewarmMs / 1000)} s |`,
    `| Complete routes | ${batch.quality.completed}/${batch.results.length} |`,
    `| Truncated discovery | ${batch.results.filter((r) => r.truncated).length}/${batch.results.length} |`,
    `| Total modeled travel time | ${number(batch.quality.totalCostSeconds, 6)} s |`,
    `| Results matching prewarm | ${batch.results.filter((r) => r.sameOutcomeAsPrewarm && r.sameTruncationAsPrewarm).length}/${batch.results.length} |`,
  ];
  if (report.catalogTraining) {
    const training = report.catalogTraining;
    rows.push(
      '| Algorithm | Approximate static-action catalog |',
      `| Excluded catalog training | ${number(training.wallMs / 1000)} s; ${training.ids.length} queries (${training.completed} complete) |`,
      `| Catalog preparation | ${training.stats.added} validated actions; ${training.stats.scopes} scopes |`,
    );
  }
  if (comparison)
    rows.push(
      `| Lost / gained solutions | ${comparison.lostSolutions.length} / ${comparison.gainedSolutions.length} |`,
      `| Geometric mean / worst cost ratio | ${number(comparison.geometricMeanCostRatio, 6)} / ${number(comparison.worstCostRatio, 6)} |`,
      ...(comparison.speedup === undefined
        ? []
        : [`| Throughput speedup vs reference | ${number(comparison.speedup)}× |`]),
    );
  if (report.qualityGate)
    rows.push(
      `| Quality gate | ${report.qualityGate.passed ? 'PASS' : `FAIL: ${cell(report.qualityGate.failures.join('; '))}`} |`,
    );
  rows.push(
    '',
    ...(report.catalogTraining
      ? [
          'Approximate algorithm: the catalog is trained before holdout prewarm and then frozen. Training time is additional preparation cost excluded from measured throughput. New queries run physical ground/resource planning over selected actions and a broad comparison of at most 128 candidates and one incumbent-local pass of at most 128 candidates. Frozen queries use physical detour pruning for each first window and retain outer comparisons across preceding window pieces; training retains both comparison phases. Completed routes are not cached.',
          '',
        ]
      : []),
    'Input loading and solver preparation are excluded. The measured batch recomputes queries after one full-batch prewarm; no completed-route cache is used. Speedup describes this workload on this machine, not a cross-scene guarantee.',
    '',
    `Revision: \`${report.revision}\`; source SHA-256: \`${report.sourceSha256}\`; Node: \`${report.node}\`.`,
    '',
    ...(report.prototype
      ? [
          `Local prototype: \`${report.prototype.implementation}\`; native scheduler: ${report.prototype.nativeLocomotion ?? false}; native ground tracing: ${report.prototype.nativeGroundTrace ?? false}; native goal geometry: ${report.prototype.nativeGoals ?? false}; native candidate search: ${report.prototype.nativeCandidate ?? false}; locomotion label limit: ${report.prototype.locomotionLabelLimit ?? 256}; prototype source SHA-256: \`${report.prototype.sourceSha256}\`.`,
          '',
        ]
      : []),
    ...(report.workingTreeDirty
      ? [
          'Measured working tree contains uncommitted changes; the source hashes identify the measured input.',
          '',
        ]
      : []),
    `Fixed solver config: \`${JSON.stringify(report.config)}\`.`,
    '',
    '| Query | Status | Modeled cost (s) |',
    '| --- | --- | ---: |',
    ...batch.results.map(
      (row) =>
        `| ${cell(row.id)} | ${cell(row.status)}${row.partial ? ' (partial)' : ''} | ${number(row.cost, 6)} |`,
    ),
    '',
  );
  return rows.join('\n');
}
